// Draws the room ahead of time: node scripts/scenes.mjs
//
//   data/scenes.json      home   the whole room, above the post list ({ head, tail })
//                         view   the window alone, beside a post ({ head, tail })
//                         moons  the moon in 30 phases, new to new, for between head and tail
//   assets/css/scene.css  every colour in the drawings, for each hour of the night
//
// The drawing is in scripts/room/; the moon's maths in assets/js/room.js, which site.js shares to
// show the reader tonight's moon. The page is always midnight; the room follows the reader's
// clock (head.html sets data-hour="2am" or "4am" on <html>, and nothing at midnight).
import { writeFileSync } from "node:fs";
import { scene, framed, colours, moonPath, TIMES, HOURS, STARS, STAR_CLEAR, CAT } from "./room/scene.mjs";
import { registry, render } from "./room/svg.mjs";
import { moonSVG } from "../assets/js/room.js";

export const VIEWS = 30;
const reg = registry();
// three pixels right, so the room's weight sits on the page's centre line; the desk's ends fade out
const DX = 3;
const scenes = {
  home: render(framed(scene(), { dx: DX, fade: 4 }), reg, { room: "home", bloom: true, falling: true, pet: true, rain: true }),
  // the home room's window, its frame and the sill, with nothing in front: 44 x 36 pixels, so
  // at 352px wide it is drawn at the room's 8px a pixel. The same night: rain and falling stars
  view: render(scene({ things: false }), reg, { room: "view", crop: { x0: 2, x1: 45, y0: 4, y1: 39 }, falling: true, rain: true }),
  moons: Array.from({ length: VIEWS }, (_, i) => moonSVG(i / VIEWS)),
  // the moon's path and the stars it passes, for head.html
  moonPath: moonPath(),
};
writeFileSync(new URL("../data/scenes.json", import.meta.url), `${JSON.stringify(scenes)}\n`);

const MOON = ["lit", "crater", "edge", "dark", "halo"];
const keys = [...reg.map.keys(), ...MOON.map((m) => "moon-" + m)];
const at = (h) => (h === TIMES[0] ? "" : `[data-hour="${h}"] `);
const css = [`/* Generated by scripts/scenes.mjs from theme/miami-rice.json. Do not edit. */`];
// midnight colours everything; a later hour only what its sky and its light change
const base = colours(TIMES[0], keys);
for (const h of TIMES) {
  const c = colours(h, keys);
  css.push(`/* ${h} */`);
  css.push(keys.filter((k) => !at(h) || c[k] !== base[k]).map((k) => `${at(h)}.scene .${reg.cls(k)}{fill:${c[k]}}`).join("\n"));
  // the window's haze on the page behind the room (main.css) takes the hour's light
  if (at(h)) css.push(`:root${at(h).trim()}{--sky:var(--${HOURS[h].glow})}`);
}
// the moon stands where head.html puts it on its path (--moon-x, --moon-y, in pixels of the
// drawing); with no script, at midnight's place
const [mx, my] = HOURS[TIMES[0]].moon;
css.push(`.scene .moon{transform:translate(calc(var(--moon-x,${mx}) * 8px),calc(var(--moon-y,${my}) * 8px))}`);
css.push(`.scene .mn-halo{fill-opacity:.1}`);
// the stars the moon is passing: head.html names them in data-hide; with no script, the ones
// near the midnight moon
css.push(STARS.map((_, n) => `[data-hide~="st${n}"] .scene .st${n}`).join(",") + `{display:none}`);
const near = STARS.flatMap(([c, r], n) => (Math.hypot(c - mx, r * 2 - my) < STAR_CLEAR ? [n] : []));
if (near.length) css.push(near.map((n) => `:root:not([data-hide]) .scene .st${n}`).join(",") + `{display:none}`);
// where the cat lies on the home page, ears pricked, in pixels of the drawing: the pet button
// (home.html) sits over it (main.css)
css.push(`.room{--cat-x:${CAT.x + DX};--cat-y:${CAT.y - 1};--cat-w:${CAT.w};--cat-h:${CAT.h + 1}}`);
// what only shows at some hours: the clock, the stars clear of the moon, the street's windows
css.push(`:root:not([data-hour]) .scene .h-${TIMES[0]},${TIMES.slice(1).map((h) => `[data-hour="${h}"] .scene .h-${h}`).join(",")}{display:none}`);
writeFileSync(new URL("../assets/css/scene.css", import.meta.url), css.join("\n") + "\n");
console.log(`home ${scenes.home.head.length + scenes.home.tail.length} B, view ${scenes.view.head.length + scenes.view.tail.length} B, moons ${scenes.moons.join("").length} B, ${keys.length} colours`);
